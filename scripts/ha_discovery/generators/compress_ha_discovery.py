#!/usr/bin/env python3
"""
Script to compress HA discovery JSONL files into C byte arrays using
chunked compression.

Each JSONL file is split into small chunks that are independently
compressed with zlib. This allows the decompressor to process data
with a small buffer instead of needing the full decompressed data
in memory at once.
"""

import json
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
from pipeline.ha_constants import CATEGORIES_LIST as CATEGORIES

FNV1A_32_PRIME = 0x01000193
FNV1A_32_OFFSET = 0x811c9dc5

def fnv1a_32(data: bytes) -> int:
    """Compute FNV-1a 32-bit hash."""
    h = FNV1A_32_OFFSET
    for b in data:
        h ^= b
        h = (h * FNV1A_32_PRIME) & 0xFFFFFFFF
    return h

# Target decompressed chunk size (must fit in decompress_buf: 18KB).
CHUNK_TARGET_DECOMPRESSED = 4000

def category_to_cpp_name(category: str) -> str:
    return category.lower()

def compress_chunk(data: bytes) -> bytes:
    return zlib.compress(data, level=9)

def split_into_chunks(raw_data: bytes) -> list:
    """Split raw data into chunks, each decompressing to <= CHUNK_TARGET_DECOMPRESSED.
    
    Returns list of (compressed_data, decompressed_size) tuples.
    """
    chunks = []
    lines = raw_data.split(b'\n')
    
    current_lines = []
    current_raw = b''
    
    for line in lines:
        if not line:
            continue
        
        test_lines = current_lines + [line]
        test_raw = b'\n'.join(test_lines) + b'\n'
        
        if len(test_raw) > CHUNK_TARGET_DECOMPRESSED and current_lines:
            chunk_compressed = compress_chunk(current_raw)
            chunks.append((chunk_compressed, len(current_raw)))
            current_lines = [line]
            current_raw = line + b'\n'
        else:
            current_lines = test_lines
            current_raw = test_raw
    
    if current_lines:
        chunk_compressed = compress_chunk(current_raw)
        chunks.append((chunk_compressed, len(current_raw)))
    
    return chunks

def bytes_to_c_array(data: bytes, indent: int = 2) -> str:
    lines = []
    indent_str = ' ' * indent
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        hex_values = ', '.join(f'0x{b:02x}' for b in chunk)
        comma = ',' if i + 16 < len(data) else ''
        lines.append(f'{indent_str}{hex_values}{comma}')
    return '\n'.join(lines)

def generate_header(input_dir: Path, header_name: str = "ha_discovery_data") -> str:
    lines = []
    lines.append('/*!')
    lines.append(' * @file')
    lines.append(' * @brief Compressed Home Assistant MQTT Discovery entity definitions.')
    lines.append(' *')
    lines.append(' * Chunked compression: each category is split into small independently-')
    lines.append(' * compressible chunks. This allows decompression with a small buffer.')
    lines.append(' *')
    lines.append(' * This file is auto-generated from ha_discovery JSONL files.')
    lines.append(' * Do not edit this file manually. Run scripts/compress_ha_discovery.py to regenerate.')
    lines.append(' */')
    lines.append('')
    guard = f"{header_name.upper()}_H"
    lines.append(f'#ifndef {guard}')
    lines.append(f'#define {guard}')
    lines.append('')
    lines.append('#include <stdint.h>')
    lines.append('#include <stddef.h>')
    lines.append('')
    lines.append('/* Chunk descriptor: offset and compressed size within category data. */')
    lines.append('typedef struct {')
    lines.append('  uint32_t offset;')
    lines.append('  uint16_t size;')
    lines.append('} ha_discovery_chunk_t;')
    lines.append('')
    lines.append('/* Category descriptor: name, data pointer, chunk table, and metadata. */')
    lines.append('typedef struct {')
    lines.append('  const char* name;')
    lines.append('  const uint8_t* data;')
    lines.append('  const ha_discovery_chunk_t* chunks;')
    lines.append('  uint16_t num_chunks;')
    lines.append('  uint16_t max_decompressed_chunk;')
    lines.append('} ha_discovery_category_t;')
    lines.append('')
    
    category_data = {}
    for category in CATEGORIES:
        jsonl_path = input_dir / f'{category}.jsonl'
        if not jsonl_path.exists():
            print(f"Warning: {jsonl_path} not found, skipping", file=sys.stderr)
            continue
        
        with open(jsonl_path, 'rb') as f:
            raw_data = f.read()
        
        chunks = split_into_chunks(raw_data)
        cpp_name = category_to_cpp_name(category)
        
        all_compressed = b''.join(c for c, _ in chunks)
        
        chunk_descriptors = []
        offset = 0
        max_decompressed = 0
        for compressed, decompressed_size in chunks:
            chunk_descriptors.append((offset, len(compressed)))
            max_decompressed = max(max_decompressed, decompressed_size)
            offset += len(compressed)
        
        category_data[cpp_name] = {
            'category': category,
            'all_compressed': all_compressed,
            'chunks': chunk_descriptors,
            'num_chunks': len(chunks),
            'max_decompressed': max_decompressed,
            'raw_size': len(raw_data),
        }
    
    for cpp_name, info in category_data.items():
        lines.append(f'// {info["category"]}.jsonl chunks')
        lines.append(f'extern const ha_discovery_chunk_t ha_discovery_chunk_{cpp_name}[];')
        lines.append('')
        
        lines.append(f'// {info["category"]}.jsonl compressed data ({len(info["all_compressed"])} bytes from {info["raw_size"]} bytes)')
        lines.append(f'extern const uint8_t ha_discovery_data_{cpp_name}[];')
        lines.append('')

    hash_input = b''.join(info['all_compressed'] for info in category_data.values())
    discovery_hash = fnv1a_32(hash_input)
    print(f"  Discovery data hash: 0x{discovery_hash:08x}", file=sys.stderr)

    lines.append('/* Category table */')
    lines.append('extern const ha_discovery_category_t ha_discovery_categories[];')
    lines.append('')
    lines.append(f'extern const uint16_t ha_discovery_category_count;')
    lines.append('')
    lines.append(f'// FNV-1a hash of all discovery data for change detection.')
    lines.append(f'// Changes when discovery definitions are updated.')
    lines.append(f'#define HA_DISCOVERY_DATA_HASH 0x{discovery_hash:08x}u')
    lines.append('')
    lines.append('#endif')
    lines.append('')

    return '\n'.join(lines)
def generate_cpp(input_dir: Path, header_name: str = "ha_discovery_data") -> str:
    """Generate a .cpp companion file with actual array definitions.

    The header contains extern const declarations; this file provides
    the definitions so the linker can resolve them.
    """
    lines = []
    lines.append(f'#include "{header_name}.h"')
    lines.append('')

    category_data = {}
    for category in CATEGORIES:
        jsonl_path = input_dir / f'{category}.jsonl'
        if not jsonl_path.exists():
            continue

        with open(jsonl_path, 'rb') as f:
            raw_data = f.read()

        chunks = split_into_chunks(raw_data)
        cpp_name = category_to_cpp_name(category)

        all_compressed = b''.join(c for c, _ in chunks)

        chunk_descriptors = []
        offset = 0
        max_decompressed = 0
        for compressed, decompressed_size in chunks:
            chunk_descriptors.append((offset, len(compressed)))
            max_decompressed = max(max_decompressed, decompressed_size)
            offset += len(compressed)

        category_data[cpp_name] = {
            'category': category,
            'all_compressed': all_compressed,
            'chunks': chunk_descriptors,
            'num_chunks': len(chunks),
            'max_decompressed': max_decompressed,
            'raw_size': len(raw_data),
        }

    for cpp_name, info in category_data.items():
        lines.append(f'// {info["category"]}.jsonl chunks')
        lines.append(f'const ha_discovery_chunk_t ha_discovery_chunk_{cpp_name}[] = {{')
        for i, (offset, size) in enumerate(info['chunks']):
            comma = ',' if i + 1 < info['num_chunks'] else ''
            lines.append(f'  {{ {offset}, {size} }}{comma}')
        lines.append('};')
        lines.append('')

        lines.append(f'// {info["category"]}.jsonl compressed data ({len(info["all_compressed"])} bytes from {info["raw_size"]} bytes)')
        lines.append(f'const uint8_t ha_discovery_data_{cpp_name}[] = {{')
        lines.append(bytes_to_c_array(info['all_compressed']))
        lines.append('};')
        lines.append('')

    lines.append('/* Category table */')
    lines.append('const ha_discovery_category_t ha_discovery_categories[] = {')
    for cpp_name, info in category_data.items():
        lines.append(f'  {{ "{info["category"]}", ha_discovery_data_{cpp_name},')
        lines.append(f'     ha_discovery_chunk_{cpp_name},')
        lines.append(f'     {info["num_chunks"]},')
        lines.append(f'     {info["max_decompressed"]} }},')
    lines.append('};')
    lines.append('')
    lines.append(f'const uint16_t ha_discovery_category_count = {len(category_data)};')
    lines.append('')

    return '\n'.join(lines)
def generate_header_to_file(input_dir: Path, output_dir: Path, header_name: str = "ha_discovery_data", extension: str = ".h") -> None:
    """Generate the compressed header and .cpp companion and write them to output_dir/components/geappliances_bridge/.

    Used by generate_erd_lists.py for in-process generation.
    output_dir is the repo root (parent of ha_discovery/).
    """
    output_file = output_dir / 'components' / 'geappliances_bridge' / f'{header_name}{extension}'
    header = generate_header(input_dir, header_name)
    print(f"Writing compressed header to {output_file}")
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, 'w') as f:
        f.write(header)

    cpp_content = generate_cpp(input_dir, header_name)
    cpp_file = output_dir / 'components' / 'geappliances_bridge' / f'{header_name}.cpp'
    print(f"Writing compressed source to {cpp_file}")
    with open(cpp_file, 'w') as f:
        f.write(cpp_content)

def main():
    import argparse
    parser = argparse.ArgumentParser(description="Compress HA discovery JSONL into C header.")
    parser.add_argument("--input-dir", default=None,
                        help="Input directory containing JSONL files (default: repo_root/ha_discovery)")
    parser.add_argument("--header-name", default="ha_discovery_data",
                        help="Base name for the output header (default: ha_discovery_data)")
    parser.add_argument("--extension", default=".h",
                        help="File extension for output (default: .h)")
    args = parser.parse_args()

    script_dir = Path(__file__).parent
    repo_root = script_dir.parent.parent.parent

    input_dir = Path(args.input_dir) if args.input_dir else repo_root / 'ha_discovery'
    output_file = repo_root / 'components' / 'geappliances_bridge' / f'{args.header_name}{args.extension}'

    if not input_dir.exists():
        print(f"Error: {input_dir} does not exist.", file=sys.stderr)
        sys.exit(1)

    jsonl_files = list(input_dir.glob('*.jsonl'))
    if not jsonl_files:
        print(f"Error: No JSONL files found in {input_dir}.", file=sys.stderr)
        sys.exit(1)

    print(f"Found {len(jsonl_files)} JSONL files in {input_dir}")

    header = generate_header(input_dir, args.header_name)

    print(f"Writing compressed header to {output_file}")
    with open(output_file, 'w') as f:
        f.write(header)

    cpp_content = generate_cpp(input_dir, args.header_name)
    cpp_file = repo_root / 'components' / 'geappliances_bridge' / f'{args.header_name}.cpp'
    print(f"Writing compressed source to {cpp_file}")
    with open(cpp_file, 'w') as f:
        f.write(cpp_content)

    total_compressed = 0
    total_uncompressed = 0
    total_chunks = 0
    max_decompressed = 0
    for category in CATEGORIES:
        jsonl_path = input_dir / f'{category}.jsonl'
        if jsonl_path.exists():
            with open(jsonl_path, 'rb') as f:
                raw_data = f.read()
            total_uncompressed += len(raw_data)
            chunks = split_into_chunks(raw_data)
            total_chunks += len(chunks)
            for compressed, decompressed_size in chunks:
                total_compressed += len(compressed)
                max_decompressed = max(max_decompressed, decompressed_size)

    ratio = total_compressed / total_uncompressed * 100 if total_uncompressed else 0
    print(f"\nCompression summary:")
    print(f"  Total uncompressed: {total_uncompressed:,} bytes")
    print(f"  Total compressed:   {total_compressed:,} bytes")
    print(f"  Total chunks:       {total_chunks}")
    print(f"  Max decompressed:   {max_decompressed:,} bytes")
    print(f"  Ratio: {ratio:.1f}%")
    print("Done!")

if __name__ == '__main__':
    main()
